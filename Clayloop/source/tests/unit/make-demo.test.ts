/**
 * Builds the bundled documented-demo session by running the real analysis pipeline over the
 * SYNTHETIC footage at 20 Hz (offline, deterministic). Only runs with MAKE_DEMO=1:
 *   npm run footage && MAKE_DEMO=1 npx vitest run tests/unit/make-demo.test.ts
 */
import { it } from 'vitest';
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import { analyzeFrame } from '../../src/cv/segment';
import { TemporalFilter } from '../../src/cv/temporal';
import { buildSession } from '../../src/store/build';
import { Sample } from '../../src/cv/types';
import { SYNTH_CAL } from './footage.test';

const RAW = 'tools/out/synthetic-128x74-20fps.rgba';
const W = 128, H = 74, FPS = 20;

it.runIf(process.env.MAKE_DEMO === '1')('build demo session', () => {
  const buf = fs.readFileSync(RAW);
  const n = Math.floor(buf.length / (W * H * 4));
  const tf = new TemporalFilter({ windowMs: 2500, noiseFloor: SYNTH_CAL.noiseFloor });
  const samples: Sample[] = [];
  let prev: Float32Array | null = null;
  for (let i = 0; i < n; i++) {
    const r = analyzeFrame(new Uint8ClampedArray(buf.buffer, buf.byteOffset + i * W * H * 4, W * H * 4), W, H, SYNTH_CAL, { prevLuma: prev });
    prev = r.luma;
    const s = tf.push((i * 1000) / FPS, r.m);
    if (i % 2 === 0) samples.push({ ...s, t: Math.round(s.t), profile: s.profile.map((v) => Math.round(v * 10000) / 10000) });
  }
  // thumbnails every 2 s
  fs.mkdirSync('tools/out/thumbs', { recursive: true });
  execFileSync('ffmpeg', ['-loglevel', 'error', '-y', '-i', 'public/demo/synthetic-footage.webm', '-vf', 'fps=0.5,scale=200:-1', '-q:v', '6', 'tools/out/thumbs/t%03d.jpg']);
  const thumbs = fs.readdirSync('tools/out/thumbs').sort().map((f, k) => ({ t: k * 2000, src: 'data:image/jpeg;base64,' + fs.readFileSync('tools/out/thumbs/' + f).toString('base64') }));
  const durationMs = samples[samples.length - 1].t;
  const { session, trace } = buildSession({
    samples, thumbs, durationMs,
    title: 'Documented demo: synthetic centering footage',
    practitioner: '', experience: '', notes: '',
    source: 'synthetic',
    provenance: 'Synthetic development footage generated by tools/make_synthetic_footage.py and analysed by ClayLoop’s own pipeline. Not empirical data: no person or clay was filmed.',
    camera: { label: 'Synthetic footage (640×360)', width: 640, height: 360 },
    calibration: SYNTH_CAL,
    hasVideo: true, videoMime: 'video/webm',
    createdAt: '2026-11-12T00:00:00.000Z',
  });
  session.id = trace.id = 'demo-synthetic';
  session.videoUrl = 'demo/synthetic-footage.webm';
  fs.writeFileSync('public/demo/demo-session.json', JSON.stringify({ format: 'clayloop-session', version: 1, exportedAt: new Date().toISOString(), session, trace }));
  fs.rmSync('public/demo/demo-video.webm', { force: true });
  console.log(`demo: ${samples.length} samples, ${session.events.length} events`);
});
